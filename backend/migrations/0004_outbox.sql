-- Step 9: transactional outbox. Every SystemEvent is written here in the
-- transaction of its state change; durable destinations get one delivery
-- row each. DDL only; webhook_outbox is dropped by 0005 once webhooks move.

CREATE TABLE outbox_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id  UUID NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    event_type  TEXT NOT NULL,
    payload     JSONB NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_outbox_events_account_type_created
    ON outbox_events (account_id, event_type, created_at DESC);
CREATE INDEX idx_outbox_events_created ON outbox_events (created_at);

CREATE TABLE outbox_deliveries (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id      BIGINT NOT NULL REFERENCES outbox_events(id) ON DELETE CASCADE,
    destination   TEXT NOT NULL,
    status        TEXT NOT NULL DEFAULT 'pending'
                  CHECK (status IN ('pending', 'delivered', 'failed')),
    attempts      INTEGER NOT NULL DEFAULT 0,
    max_attempts  INTEGER NOT NULL DEFAULT 10,
    available_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    delivered_at  TIMESTAMPTZ,
    last_error    TEXT,
    CONSTRAINT uq_outbox_delivery UNIQUE (event_id, destination)
);

CREATE INDEX idx_outbox_deliveries_pending
    ON outbox_deliveries (available_at) WHERE status = 'pending';
CREATE INDEX idx_outbox_deliveries_event ON outbox_deliveries (event_id);

-- NOTIFY from a trigger (as 0003 does for jobs): it fires only for real
-- inserts and PostgreSQL delivers it at commit, never for a rollback.
CREATE FUNCTION outbox_notify() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    PERFORM pg_notify('outbox', NEW.id::text || ':' || NEW.account_id::text);
    RETURN NULL;
END $$;

CREATE TRIGGER outbox_events_notify AFTER INSERT ON outbox_events
    FOR EACH ROW EXECUTE FUNCTION outbox_notify();
