-- Step 11: Second Brain & Knowledge Base subsystem.
-- Dedicated notes table and unified vector embeddings across notes, bookmarks, journals, and footprints.
--
-- Notes keep Markdown in `content` as the single source of truth. Everything
-- else search needs is derived from it on write and can be rebuilt from it:
-- content_hash, search_text, excerpt, the generated search_vector and the
-- trigram index. indexed_content_hash/indexed_at record which body the
-- embeddings were built from. The derived columns are NOT NULL because the
-- service derives them on every write.

CREATE EXTENSION IF NOT EXISTS vector;
CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE TABLE notes (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id             UUID NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    title                TEXT NOT NULL,
    content              TEXT NOT NULL,
    format               TEXT NOT NULL DEFAULT 'markdown'
                         CHECK (format = 'markdown'),
    source_channel       TEXT NOT NULL DEFAULT 'web'
                         CHECK (source_channel IN ('matrix', 'discord', 'telegram', 'email', 'web', 'mcp')),
    source_ref           TEXT,
    tags                 TEXT[] NOT NULL DEFAULT '{}',
    is_archived          BOOLEAN NOT NULL DEFAULT FALSE,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    note_type            TEXT NOT NULL DEFAULT 'note'
                         CHECK (note_type IN ('note','idea','fact','observation','decision')),
    content_hash         TEXT NOT NULL,
    search_text          TEXT NOT NULL,
    excerpt              TEXT NOT NULL,
    indexed_content_hash TEXT,
    indexed_at           TIMESTAMPTZ,
    search_vector        tsvector GENERATED ALWAYS AS (
        setweight(to_tsvector('simple', title), 'A') ||
        setweight(to_tsvector('simple', search_text), 'B')
    ) STORED
);

CREATE INDEX idx_notes_owner_updated ON notes (owner_id, updated_at DESC);
CREATE INDEX idx_notes_tags ON notes USING GIN (tags);
CREATE INDEX idx_notes_search_vector ON notes USING GIN (search_vector);
CREATE INDEX idx_notes_search_trgm
    ON notes USING GIN ((title || ' ' || search_text) gin_trgm_ops);

CREATE TABLE knowledge_embeddings (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id        UUID NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    item_type       TEXT NOT NULL
                    CHECK (item_type IN ('note', 'bookmark', 'journal', 'footprint')),
    item_id         BIGINT NOT NULL,
    chunk_index     INTEGER NOT NULL DEFAULT 0,
    content_snippet TEXT NOT NULL,
    embedding       vector(384) NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    -- Which model produced each chunk, so a model switch can find stale chunks.
    embedding_model TEXT NOT NULL DEFAULT 'bge-small-en-v1.5',
    CONSTRAINT uq_knowledge_chunk UNIQUE (owner_id, item_type, item_id, chunk_index)
);

CREATE INDEX idx_knowledge_embeddings_owner ON knowledge_embeddings (owner_id, item_type);
CREATE INDEX idx_knowledge_embeddings_vector
    ON knowledge_embeddings USING hnsw (embedding vector_cosine_ops)
    WITH (m = 16, ef_construction = 64);
CREATE INDEX idx_knowledge_embeddings_model ON knowledge_embeddings (embedding_model);
