-- Step 11: Second Brain & Knowledge Base subsystem.
-- Dedicated notes table and unified vector embeddings across notes, bookmarks, journals, and footprints.

CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE notes (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id        UUID NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    title           TEXT NOT NULL,
    content         TEXT NOT NULL,
    format          TEXT NOT NULL DEFAULT 'markdown'
                    CHECK (format IN ('markdown', 'plain', 'quote')),
    source_channel  TEXT NOT NULL DEFAULT 'web'
                    CHECK (source_channel IN ('matrix', 'discord', 'telegram', 'email', 'web', 'mcp')),
    source_ref      TEXT,
    tags            TEXT[] NOT NULL DEFAULT '{}',
    is_archived     BOOLEAN NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_notes_owner_updated ON notes (owner_id, updated_at DESC);
CREATE INDEX idx_notes_tags ON notes USING GIN (tags);
CREATE INDEX idx_notes_search ON notes USING GIN (to_tsvector('english', title || ' ' || content));

CREATE TABLE knowledge_embeddings (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id        UUID NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    item_type       TEXT NOT NULL
                    CHECK (item_type IN ('note', 'bookmark', 'journal', 'footprint')),
    item_id         BIGINT NOT NULL,
    chunk_index     INTEGER NOT NULL DEFAULT 0,
    content_snippet TEXT NOT NULL,
    embedding       vector(384) NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_knowledge_chunk UNIQUE (owner_id, item_type, item_id, chunk_index)
);

CREATE INDEX idx_knowledge_embeddings_owner ON knowledge_embeddings (owner_id, item_type);
CREATE INDEX idx_knowledge_embeddings_vector 
    ON knowledge_embeddings USING hnsw (embedding vector_cosine_ops)
    WITH (m = 16, ef_construction = 64);
